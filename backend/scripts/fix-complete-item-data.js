const dataPath = path.join(__dirname, '..', 'data', 'items.seed.json');

console.log('📖 Reading items.seed.json...\n');
const items = JSON.parse(fs.readFileSync(dataPath, 'utf-8'));

let qualityFixes = 0;
let typeFixes = 0;
let trinketFixes = 0;

items.forEach(item => {
  const slug = item.slug;
  
  // Check if this should be a trinket
  if (allTrinkets.includes(slug)) {
    if (item.item_type !== 'trinket') {
      console.log(`Type fix: ${item.name} (${slug}): ${item.item_type} -> trinket`);
      item.item_type = 'trinket';
      typeFixes++;
    }
    // Trinkets don't have quality
    if (item.quality !== null) {
      console.log(`Quality fix: ${item.name} (${slug}): ${item.quality} -> null (trinket)`);
      item.quality = null;
      trinketFixes++;
    }
    return;
  }
  
  // Check if we have official data for this item
  if (officialItemData[slug]) {
    const official = officialItemData[slug];
    
    // Fix quality if different
    if (item.quality !== official.quality) {
      console.log(`Quality fix: ${item.name} (${slug}): ${item.quality} -> ${official.quality}`);
      item.quality = official.quality;
      qualityFixes++;
    }
    
    // Fix type if different
    if (item.item_type !== official.type && official.type !== 'trinket') {
      console.log(`Type fix: ${item.name} (${slug}): ${item.item_type} -> ${official.type}`);
      item.item_type = official.type;
      typeFixes++;
    }
  }
});

// Save the fixed data
console.log('\n💾 Saving fixed items.seed.json...\n');
fs.writeFileSync(dataPath, JSON.stringify(items, null, 2));

